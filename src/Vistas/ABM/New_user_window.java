    private void view_pass_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_view_pass_buttonActionPerformed
        if (color == 0) {
            ImageIcon icon1 = new ImageIcon(getClass().getResource("/Recursos/view_pass2.png"));
            ImageIcon icon2 = new ImageIcon(getClass().getResource("/Recursos/view_pass.png"));
            char caracterActual = password_text.getEchoChar();
            if (caracterActual != (char) 0) {
                password_text.setEchoChar((char) 0);
                view_pass_button.setIcon(icon1);
            } else {
                password_text.setEchoChar(caracterEchoPredeterminado);
                view_pass_button.setIcon(icon2);
            }
        } else if (color == 1) {
            char caracterActual = password_text.getEchoChar();
            if (caracterActual != (char) 0) {
                password_text.setEchoChar((char) 0);
                view_pass_button.setIcon(icondark);
            } else {
                password_text.setEchoChar(caracterEchoPredeterminado);
                view_pass_button.setIcon(icondark2);
            }
        }
    }//GEN-LAST:event_view_pass_buttonActionPerformed

