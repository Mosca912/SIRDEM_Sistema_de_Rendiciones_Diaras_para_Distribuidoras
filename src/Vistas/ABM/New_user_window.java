    private void save_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_save_buttonActionPerformed
        String nomb = username_text.getText();
        String ps = password_text.getText();
        String rps = repeat_password_text.getText();
        String em = email_text.getText();
        String dni = dni_text.getText();
        if (!nomb.trim().isEmpty() && !ps.trim().isEmpty() && !rps.trim().isEmpty() && !em.trim().isEmpty() && rankId != 0 && !dni.trim().isEmpty()) {
            if (em.contains("@") && em.contains(".")) {
                if (ps.equals(rps)) {
                    try {
                        int cerrar = Clases.Add_modify_user.AddNewUser(con, nomb, ps, rps, em, 1, flag, userId, estado, dni);
                        if (cerrar == 1) {
                            new Menu_window().setVisible(true);
                            this.dispose();
                        }
                    } catch (SQLException e) {
                        JOptionPane.showMessageDialog(null, "ERROR AL REGISTRAR: " + e);
                    }
                } else {
                    JOptionPane.showMessageDialog(null, "Las contraseñas no coinciden!");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Introduzca un correo valido!");
            }

        } else {
            JOptionPane.showMessageDialog(null, "¡HAY CAMPOS VACIOS! Por favor, revise");
        }
    }//GEN-LAST:event_save_buttonActionPerformed

